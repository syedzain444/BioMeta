COLUMN check_out FORMAT A20
COLUMN punch_count FORMAT 999

PROMPT === Raw punches for EMPLOYEE_ID 5001 (last 60 days) ===
SELECT punch_time, work_code, status, authority, device_serial FROM (
SELECT TO_CHAR(PUNCH_TIME, 'YYYY-MM-DD HH24:MI:SS') AS punch_time,
       WORK_CODE, STATUS, AUTHORITY, DEVICE_SERIAL, PUNCH_TIME pt
FROM BIOMETRIC_ATTENDANCE_LOG
WHERE TRIM(EMPLOYEE_ID) IN ('5001', '05001')
   OR LTRIM(TRIM(EMPLOYEE_ID), '0') = '5001'
ORDER BY PUNCH_TIME DESC
) WHERE ROWNUM <= 50;

PROMPT
PROMPT === Daily check-in (first punch) / check-out (last punch) ===
SELECT punch_day, check_in, check_out, punch_count FROM (
SELECT TRUNC(PUNCH_TIME) AS punch_day,
       TO_CHAR(MIN(PUNCH_TIME), 'YYYY-MM-DD HH24:MI:SS') AS check_in,
       CASE WHEN COUNT(*) > 1 THEN TO_CHAR(MAX(PUNCH_TIME), 'YYYY-MM-DD HH24:MI:SS') END AS check_out,
       COUNT(*) AS punch_count
FROM BIOMETRIC_ATTENDANCE_LOG
WHERE TRIM(EMPLOYEE_ID) IN ('5001', '05001')
   OR LTRIM(TRIM(EMPLOYEE_ID), '0') = '5001'
GROUP BY TRUNC(PUNCH_TIME)
ORDER BY punch_day DESC
) WHERE ROWNUM <= 30;

EXIT;
