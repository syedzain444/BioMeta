PROMPT TOTAL:
SELECT COUNT(*) FROM BIOMETRIC_ATTENDANCE_LOG;
PROMPT MIN MAX:
SELECT MIN(PUNCH_TIME), MAX(PUNCH_TIME) FROM BIOMETRIC_ATTENDANCE_LOG;
PROMPT IDS ALL TIME:
SELECT TRIM(EMPLOYEE_ID) id, COUNT(*) c FROM BIOMETRIC_ATTENDANCE_LOG
WHERE TRIM(EMPLOYEE_ID) IN ('5001','5002','5003','5004') OR LTRIM(TRIM(EMPLOYEE_ID),'0') IN ('5001','5002','5003','5004')
GROUP BY TRIM(EMPLOYEE_ID);
PROMPT IDS 2026 OCT-NOV:
SELECT TRIM(EMPLOYEE_ID) id, COUNT(*) c FROM BIOMETRIC_ATTENDANCE_LOG
WHERE PUNCH_TIME >= TO_DATE('2026-10-01','YYYY-MM-DD') AND PUNCH_TIME < TO_DATE('2026-11-05','YYYY-MM-DD')
AND (TRIM(EMPLOYEE_ID) IN ('5001','5002','5003','5004') OR LTRIM(TRIM(EMPLOYEE_ID),'0') IN ('5001','5002','5003','5004'))
GROUP BY TRIM(EMPLOYEE_ID);
EXIT;
