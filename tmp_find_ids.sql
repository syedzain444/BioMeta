SET PAGESIZE 100 FEEDBACK OFF
SELECT * FROM (
  SELECT DISTINCT TRIM(EMPLOYEE_ID) id FROM BIOMETRIC_ATTENDANCE_LOG
  WHERE REGEXP_LIKE(TRIM(EMPLOYEE_ID), '^0*500[1-4]$')
  ORDER BY id
);
SELECT * FROM (
  SELECT TRIM(EMPLOYEE_ID) id, COUNT(*) c
  FROM BIOMETRIC_ATTENDANCE_LOG
  WHERE PUNCH_TIME >= TO_DATE('2026-10-01','YYYY-MM-DD')
    AND PUNCH_TIME < TO_DATE('2026-11-05','YYYY-MM-DD')
  GROUP BY TRIM(EMPLOYEE_ID)
  ORDER BY c DESC
) WHERE ROWNUM <= 15;
EXIT;
