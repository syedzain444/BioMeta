SET PAGESIZE 5000 LINESIZE 220 FEEDBACK OFF VERIFY OFF TRIMSPOOL ON
SET COLSEP |
SPOOL "d:\Zain BTK Projects\Biometric\output\checkin_checkout_oracle_spool.csv"

PROMPT employee_id|employee_name|date|check_in|check_out|punch_count
SELECT TRIM(EMPLOYEE_ID) || '|' ||
       REPLACE(NVL(EMPLOYEE_NAME,' '), '|', ' ') || '|' ||
       TO_CHAR(TRUNC(PUNCH_TIME), 'YYYY-MM-DD') || '|' ||
       TO_CHAR(MIN(PUNCH_TIME), 'YYYY-MM-DD HH24:MI:SS') || '|' ||
       CASE WHEN COUNT(*) > 1 THEN TO_CHAR(MAX(PUNCH_TIME), 'YYYY-MM-DD HH24:MI:SS') ELSE '' END || '|' ||
       COUNT(*)
FROM BIOMETRIC_ATTENDANCE_LOG
WHERE PUNCH_TIME >= TO_DATE('2025-10-01 00:00:00', 'YYYY-MM-DD HH24:MI:SS')
  AND PUNCH_TIME <  TO_DATE('2025-11-05 00:00:00', 'YYYY-MM-DD HH24:MI:SS')
  AND (
        TRIM(EMPLOYEE_ID) IN ('5001','5002','5003','5004')
     OR LTRIM(TRIM(EMPLOYEE_ID), '0') IN ('5001','5002','5003','5004')
      )
GROUP BY TRIM(EMPLOYEE_ID), NVL(EMPLOYEE_NAME,' '), TRUNC(PUNCH_TIME)
ORDER BY 1, TRUNC(PUNCH_TIME);

SPOOL OFF
EXIT;
