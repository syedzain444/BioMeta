BEGIN IF :NEW.ROLE_ID IS NULL OR :NEW.ROLE_ID = 0 THEN SELECT SEC_ROLE_SEQ.NEXTVAL INTO :NEW.ROLE_ID FROM DUAL; END IF; END;
