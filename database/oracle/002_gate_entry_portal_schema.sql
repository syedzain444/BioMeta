BEFORE INSERT ON SEC_USER FOR EACH ROW
BEGIN IF :NEW.USER_ID IS NULL OR :NEW.USER_ID = 0 THEN SELECT SEC_USER_SEQ.NEXTVAL INTO :NEW.USER_ID FROM DUAL; END IF; END;
/
