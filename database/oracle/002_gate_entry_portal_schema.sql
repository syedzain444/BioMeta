-- ========== SEQUENCES ==========
CREATE SEQUENCE SEC_USER_SEQ START WITH 1 INCREMENT BY 1 NOCACHE NOCYCLE;
CREATE SEQUENCE SEC_ROLE_SEQ START WITH 1 INCREMENT BY 1 NOCACHE NOCYCLE;
CREATE SEQUENCE SEC_MODULE_SEQ START WITH 1 INCREMENT BY 1 NOCACHE NOCYCLE;
CREATE SEQUENCE SEC_PERMISSION_SEQ START WITH 1 INCREMENT BY 1 NOCACHE NOCYCLE;
CREATE SEQUENCE BIOMETRIC_ATTENDANCE_LOG_SEQ START WITH 1 INCREMENT BY 1 NOCACHE NOCYCLE;

-- ========== SEC_MODULE ==========
CREATE TABLE SEC_MODULE (
  MODULE_ID     NUMBER(18)     NOT NULL,
  MODULE_CODE   VARCHAR2(64)   NOT NULL,
  MODULE_NAME   VARCHAR2(128)  NOT NULL,
  ROUTE_PATH    VARCHAR2(256),
  ICON_CLASS    VARCHAR2(64),
  SORT_ORDER    NUMBER(5)      DEFAULT 0 NOT NULL,
  IS_ACTIVE     CHAR(1)        DEFAULT 'Y' NOT NULL,
  CREATED_BY    NUMBER(18),
  UPDATED_BY    NUMBER(18),
  DELETED_BY    NUMBER(18),
  CREATED_AT    TIMESTAMP(6)   DEFAULT SYSTIMESTAMP NOT NULL,
  UPDATED_AT    TIMESTAMP(6),
  DELETED_AT    TIMESTAMP(6),
  CONSTRAINT PK_SEC_MODULE PRIMARY KEY (MODULE_ID),
  CONSTRAINT UK_SEC_MODULE_CODE UNIQUE (MODULE_CODE),
  CONSTRAINT CK_SEC_MODULE_ACTIVE CHECK (IS_ACTIVE IN ('Y','N'))
);

-- ========== SEC_PERMISSION ==========
CREATE TABLE SEC_PERMISSION (
  PERMISSION_ID     NUMBER(18)     NOT NULL,
  MODULE_ID         NUMBER(18)     NOT NULL,
  PERMISSION_CODE   VARCHAR2(128)  NOT NULL,
  PERMISSION_NAME   VARCHAR2(256)  NOT NULL,
  DESCRIPTION       VARCHAR2(512),
  IS_ACTIVE         CHAR(1)        DEFAULT 'Y' NOT NULL,
  CREATED_BY        NUMBER(18),
  UPDATED_BY        NUMBER(18),
  DELETED_BY        NUMBER(18),
  CREATED_AT        TIMESTAMP(6)   DEFAULT SYSTIMESTAMP NOT NULL,
  UPDATED_AT        TIMESTAMP(6),
  DELETED_AT        TIMESTAMP(6),
  CONSTRAINT PK_SEC_PERMISSION PRIMARY KEY (PERMISSION_ID),
  CONSTRAINT UK_SEC_PERM_CODE UNIQUE (PERMISSION_CODE),
  CONSTRAINT FK_SEC_PERM_MODULE FOREIGN KEY (MODULE_ID) REFERENCES SEC_MODULE (MODULE_ID)
);

-- ========== SEC_ROLE ==========
CREATE TABLE SEC_ROLE (
  ROLE_ID       NUMBER(18)     NOT NULL,
  ROLE_CODE     VARCHAR2(64)   NOT NULL,
  ROLE_NAME     VARCHAR2(128)  NOT NULL,
  DESCRIPTION   VARCHAR2(512),
  IS_SYSTEM     CHAR(1)        DEFAULT 'N' NOT NULL,
  IS_ACTIVE     CHAR(1)        DEFAULT 'Y' NOT NULL,
  CREATED_BY    NUMBER(18),
  UPDATED_BY    NUMBER(18),
  DELETED_BY    NUMBER(18),
  CREATED_AT    TIMESTAMP(6)   DEFAULT SYSTIMESTAMP NOT NULL,
  UPDATED_AT    TIMESTAMP(6),
  DELETED_AT    TIMESTAMP(6),
  CONSTRAINT PK_SEC_ROLE PRIMARY KEY (ROLE_ID),
  CONSTRAINT UK_SEC_ROLE_CODE UNIQUE (ROLE_CODE),
  CONSTRAINT CK_SEC_ROLE_SYS CHECK (IS_SYSTEM IN ('Y','N')),
  CONSTRAINT CK_SEC_ROLE_ACTIVE CHECK (IS_ACTIVE IN ('Y','N'))
);

-- ========== SEC_USER ==========
CREATE TABLE SEC_USER (
  USER_ID         NUMBER(18)     NOT NULL,
  EMPLOYEE_ID     VARCHAR2(32)   NOT NULL,
  PASSWORD_HASH   VARCHAR2(256)  NOT NULL,
  DISPLAY_NAME    VARCHAR2(128)  NOT NULL,
  EMAIL           VARCHAR2(256),
  IS_ACTIVE       CHAR(1)        DEFAULT 'Y' NOT NULL,
  MUST_CHANGE_PWD CHAR(1)        DEFAULT 'N' NOT NULL,
  LAST_LOGIN_AT   TIMESTAMP(6),
  CREATED_BY      NUMBER(18),
  UPDATED_BY      NUMBER(18),
  DELETED_BY      NUMBER(18),
  CREATED_AT      TIMESTAMP(6)   DEFAULT SYSTIMESTAMP NOT NULL,
  UPDATED_AT      TIMESTAMP(6),
  DELETED_AT      TIMESTAMP(6),
  CONSTRAINT PK_SEC_USER PRIMARY KEY (USER_ID),
  CONSTRAINT UK_SEC_USER_EMP_ID UNIQUE (EMPLOYEE_ID),
  CONSTRAINT CK_SEC_USER_ACTIVE CHECK (IS_ACTIVE IN ('Y','N'))
);

-- ========== SEC_USER_ROLE ==========
CREATE TABLE SEC_USER_ROLE (
  USER_ID     NUMBER(18) NOT NULL,
  ROLE_ID     NUMBER(18) NOT NULL,
  CREATED_BY  NUMBER(18),
  UPDATED_BY  NUMBER(18),
  DELETED_BY  NUMBER(18),
  CREATED_AT  TIMESTAMP(6) DEFAULT SYSTIMESTAMP NOT NULL,
  UPDATED_AT  TIMESTAMP(6),
  DELETED_AT  TIMESTAMP(6),
  CONSTRAINT PK_SEC_USER_ROLE PRIMARY KEY (USER_ID, ROLE_ID),
  CONSTRAINT FK_SUR_USER FOREIGN KEY (USER_ID) REFERENCES SEC_USER (USER_ID),
  CONSTRAINT FK_SUR_ROLE FOREIGN KEY (ROLE_ID) REFERENCES SEC_ROLE (ROLE_ID)
);

-- ========== SEC_ROLE_PERMISSION ==========
CREATE TABLE SEC_ROLE_PERMISSION (
  ROLE_ID         NUMBER(18) NOT NULL,
  PERMISSION_ID   NUMBER(18) NOT NULL,
  CREATED_BY      NUMBER(18),
  UPDATED_BY      NUMBER(18),
  DELETED_BY      NUMBER(18),
  CREATED_AT      TIMESTAMP(6) DEFAULT SYSTIMESTAMP NOT NULL,
  UPDATED_AT      TIMESTAMP(6),
  DELETED_AT      TIMESTAMP(6),
  CONSTRAINT PK_SEC_ROLE_PERM PRIMARY KEY (ROLE_ID, PERMISSION_ID),
  CONSTRAINT FK_SRP_ROLE FOREIGN KEY (ROLE_ID) REFERENCES SEC_ROLE (ROLE_ID),
  CONSTRAINT FK_SRP_PERM FOREIGN KEY (PERMISSION_ID) REFERENCES SEC_PERMISSION (PERMISSION_ID)
);

-- ========== BIOMETRIC_ATTENDANCE_LOG ==========
CREATE TABLE BIOMETRIC_ATTENDANCE_LOG (
  LOG_ID         NUMBER(18)      NOT NULL,
  EMPLOYEE_ID    VARCHAR2(32)    NOT NULL,
  EMPLOYEE_NAME  VARCHAR2(128),
  PUNCH_TIME     DATE            NOT NULL,
  WORK_CODE      VARCHAR2(32),
  STATUS         VARCHAR2(32),
  AUTHORITY      VARCHAR2(32),
  CARD_SOURCE    VARCHAR2(64),
  DEVICE_SERIAL  VARCHAR2(64),
  SYNCED_AT      TIMESTAMP(6)    DEFAULT SYSTIMESTAMP NOT NULL,
  DEDUPE_KEY     VARCHAR2(64)    NOT NULL,
  CREATED_BY     NUMBER(18),
  UPDATED_BY     NUMBER(18),
  DELETED_BY     NUMBER(18),
  CREATED_AT     TIMESTAMP(6)    DEFAULT SYSTIMESTAMP NOT NULL,
  UPDATED_AT     TIMESTAMP(6),
  DELETED_AT     TIMESTAMP(6),
  CONSTRAINT PK_BIOMETRIC_ATT_LOG PRIMARY KEY (LOG_ID),
  CONSTRAINT UK_BIOMETRIC_DEDUPE UNIQUE (DEDUPE_KEY)
);

CREATE INDEX IX_BIO_ATT_PUNCH_TIME ON BIOMETRIC_ATTENDANCE_LOG (PUNCH_TIME);
-- EMPLOYEE_ID already indexed by UK_SEC_USER_EMP_ID (UNIQUE) — extra index not needed (ORA-01408).

-- ========== TRIGGERS (PK ids) ==========
CREATE OR REPLACE TRIGGER TRG_SEC_MODULE_BI
BEFORE INSERT ON SEC_MODULE FOR EACH ROW
BEGIN IF :NEW.MODULE_ID IS NULL OR :NEW.MODULE_ID = 0 THEN SELECT SEC_MODULE_SEQ.NEXTVAL INTO :NEW.MODULE_ID FROM DUAL; END IF; END;
/
