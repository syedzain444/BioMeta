-- Nav module: employee photo lookup (HDCP GetEmployee / photo_data).
-- Run once on GateEntryOracle schema.

INSERT INTO SEC_MODULE (MODULE_CODE, MODULE_NAME, ROUTE_PATH, ICON_CLASS, SORT_ORDER, CREATED_BY)
SELECT 'device_photos', 'Employee photos', '/Device/EmployeePhotos', 'bi-camera', 36, 1 FROM DUAL
WHERE NOT EXISTS (SELECT 1 FROM SEC_MODULE WHERE MODULE_CODE = 'device_photos');

INSERT INTO SEC_PERMISSION (MODULE_ID, PERMISSION_CODE, PERMISSION_NAME, CREATED_BY)
SELECT m.MODULE_ID, 'device_photos.view', 'View employee photos from device', 1 FROM SEC_MODULE m
WHERE m.MODULE_CODE = 'device_photos'
  AND NOT EXISTS (SELECT 1 FROM SEC_PERMISSION WHERE PERMISSION_CODE = 'device_photos.view');

INSERT INTO SEC_ROLE_PERMISSION (ROLE_ID, PERMISSION_ID, CREATED_BY)
SELECT r.ROLE_ID, p.PERMISSION_ID, 1
FROM SEC_ROLE r
CROSS JOIN SEC_PERMISSION p
WHERE r.ROLE_CODE = 'SUPER_ADMIN' AND p.PERMISSION_CODE = 'device_photos.view'
  AND NOT EXISTS (
    SELECT 1 FROM SEC_ROLE_PERMISSION rp
    WHERE rp.ROLE_ID = r.ROLE_ID AND rp.PERMISSION_ID = p.PERMISSION_ID AND rp.DELETED_AT IS NULL
  );

INSERT INTO SEC_ROLE_PERMISSION (ROLE_ID, PERMISSION_ID, CREATED_BY)
SELECT DISTINCT rp.ROLE_ID, p_new.PERMISSION_ID, 1
FROM SEC_ROLE_PERMISSION rp
JOIN SEC_PERMISSION p_dev ON p_dev.PERMISSION_ID = rp.PERMISSION_ID AND p_dev.PERMISSION_CODE = 'device_users.view' AND p_dev.DELETED_AT IS NULL
CROSS JOIN SEC_PERMISSION p_new
WHERE p_new.PERMISSION_CODE = 'device_photos.view' AND p_new.DELETED_AT IS NULL
  AND rp.DELETED_AT IS NULL
  AND NOT EXISTS (
    SELECT 1 FROM SEC_ROLE_PERMISSION x
    WHERE x.ROLE_ID = rp.ROLE_ID AND x.PERMISSION_ID = p_new.PERMISSION_ID AND x.DELETED_AT IS NULL
  );

COMMIT;