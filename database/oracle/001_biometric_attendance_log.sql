CREATE SEQUENCE BIOMETRIC_ATTENDANCE_LOG_SEQ  START WITH 1 INCREMENT BY 1 NOCACHE NOCYCLE;

CREATE TABLE BIOMETRIC_ATTENDANCE_LOG (
  LOG_ID         NUMBER(18)      NOT NULL,
  EMPLOYEE_ID    VARCHAR2(32)    NOT NULL,
  EMPLOYEE_NAME  VARCHAR2(128),
  PUNCH_TIME     DATE            NOT NULL,
  WORK_CODE      VARCHAR2(32),
  STATUS         VARCHAR2(32),
  AUTHORITY      VARCHAR2(32),
  CARD_SOURCE    VARCHAR2(64),
  DEVICE_SERIAL  VARCHAR2(64),
  SYNCED_AT      TIMESTAMP(6)    DEFAULT SYSTIMESTAMP NOT NULL,
  DEDUPE_KEY     VARCHAR2(64)    NOT NULL,
  CONSTRAINT PK_BIOMETRIC_ATT_LOG PRIMARY KEY (LOG_ID),
  CONSTRAINT UK_BIOMETRIC_DEDUPE UNIQUE (DEDUPE_KEY)
);

CREATE INDEX IX_BIO_ATT_PUNCH_TIME ON BIOMETRIC_ATTENDANCE_LOG (PUNCH_TIME);

CREATE OR REPLACE TRIGGER TRG_BIOMETRIC_ATT_LOG_BI
BEFORE INSERT ON BIOMETRIC_ATTENDANCE_LOG
FOR EACH ROW
BEGIN
  IF :NEW.LOG_ID IS NULL OR :NEW.LOG_ID = 0 THEN
    SELECT BIOMETRIC_ATTENDANCE_LOG_SEQ.NEXTVAL INTO :NEW.LOG_ID FROM DUAL;
  END IF;
END;
/

