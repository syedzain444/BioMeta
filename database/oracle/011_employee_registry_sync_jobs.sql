-- Employee registry (portal master) + sync job history (upload / verify / delete).
-- Run on GateEntryOracle schema (entrygate_surv).

CREATE SEQUENCE BIO_EMP_REGISTRY_SEQ START WITH 1 INCREMENT BY 1 NOCACHE NOCYCLE;

CREATE TABLE BIO_EMPLOYEE_REGISTRY (
  REGISTRY_ID       NUMBER(18)       NOT NULL,
  EMPLOYEE_ID       VARCHAR2(32)     NOT NULL,
  DISPLAY_NAME      VARCHAR2(200),
  DEPARTMENT        VARCHAR2(200),
  CARD_NUMBER       VARCHAR2(64),
  AUTHORITY         VARCHAR2(32),
  DEFAULT_DEVICE_ID NUMBER(18),
  BIOMETRIC_STATUS  VARCHAR2(48),
  HAS_FACE_DATA     CHAR(1) DEFAULT 'N' NOT NULL,
  SOURCE_TAG        VARCHAR2(64),
  CREATED_BY        NUMBER(18),
  UPDATED_BY        NUMBER(18),
  CREATED_AT        TIMESTAMP DEFAULT SYSTIMESTAMP NOT NULL,
  UPDATED_AT        TIMESTAMP DEFAULT SYSTIMESTAMP NOT NULL,
  DELETED_AT        TIMESTAMP,
  CONSTRAINT PK_BIO_EMP_REGISTRY PRIMARY KEY (REGISTRY_ID),
  CONSTRAINT CK_BIO_EMP_FACE CHECK (HAS_FACE_DATA IN ('Y','N'))
);

CREATE INDEX IX_BIO_EMP_REG_EMP_ID ON BIO_EMPLOYEE_REGISTRY (EMPLOYEE_ID);

CREATE INDEX IX_BIO_EMP_REG_DEVICE ON BIO_EMPLOYEE_REGISTRY (DEFAULT_DEVICE_ID);

CREATE OR REPLACE TRIGGER TRG_BIO_EMP_REGISTRY_BI
BEFORE INSERT ON BIO_EMPLOYEE_REGISTRY FOR EACH ROW
BEGIN
  IF :NEW.REGISTRY_ID IS NULL OR :NEW.REGISTRY_ID = 0 THEN
    SELECT BIO_EMP_REGISTRY_SEQ.NEXTVAL INTO :NEW.REGISTRY_ID FROM DUAL;
  END IF;
  :NEW.CREATED_AT := NVL(:NEW.CREATED_AT, SYSTIMESTAMP);
  :NEW.UPDATED_AT := SYSTIMESTAMP;
END;
/

CREATE TABLE BIO_EMPLOYEE_SYNC_JOB (
  JOB_ID          VARCHAR2(36)  NOT NULL,
  JOB_KIND        VARCHAR2(32)  DEFAULT 'upload' NOT NULL,
  BIO_DEVICE_ID   NUMBER(18)    NOT NULL,
  DEVICE_NAME     VARCHAR2(200),
  DEVICE_IP       VARCHAR2(64),
  STATE           VARCHAR2(32)  NOT NULL,
  TOTAL_COUNT     NUMBER(10)    DEFAULT 0 NOT NULL,
  UPLOADED_COUNT  NUMBER(10)    DEFAULT 0 NOT NULL,
  FAILED_COUNT    NUMBER(10)    DEFAULT 0 NOT NULL,
  VERIFIED_COUNT  NUMBER(10)    DEFAULT 0 NOT NULL,
  DELETED_COUNT   NUMBER(10)    DEFAULT 0 NOT NULL,
  LOG_LINE        VARCHAR2(4000),
  LAST_ERROR      VARCHAR2(4000),
  CREATED_BY      NUMBER(18),
  CREATED_AT      TIMESTAMP DEFAULT SYSTIMESTAMP NOT NULL,
  UPDATED_AT      TIMESTAMP DEFAULT SYSTIMESTAMP NOT NULL,
  COMPLETED_AT    TIMESTAMP,
  CONSTRAINT PK_BIO_EMP_SYNC_JOB PRIMARY KEY (JOB_ID)
);

CREATE INDEX IX_BIO_EMP_SYNC_JOB_DEV ON BIO_EMPLOYEE_SYNC_JOB (BIO_DEVICE_ID, CREATED_AT DESC);

CREATE SEQUENCE BIO_EMP_SYNC_LINE_SEQ START WITH 1 INCREMENT BY 1 NOCACHE NOCYCLE;

CREATE TABLE BIO_EMPLOYEE_SYNC_LINE (
  LINE_ID       NUMBER(18)    NOT NULL,
  JOB_ID        VARCHAR2(36)  NOT NULL,
  EMPLOYEE_ID   VARCHAR2(32)  NOT NULL,
  DISPLAY_NAME  VARCHAR2(200),
  SUCCEEDED     CHAR(1)       DEFAULT 'N' NOT NULL,
  VERIFIED      CHAR(1)       DEFAULT 'N' NOT NULL,
  METHOD        VARCHAR2(64),
  ERROR_MSG     VARCHAR2(2000),
  SORT_ORDER    NUMBER(10)    DEFAULT 0 NOT NULL,
  CONSTRAINT PK_BIO_EMP_SYNC_LINE PRIMARY KEY (LINE_ID),
  CONSTRAINT FK_BIO_EMP_SYNC_LINE_JOB FOREIGN KEY (JOB_ID) REFERENCES BIO_EMPLOYEE_SYNC_JOB (JOB_ID)
);

CREATE INDEX IX_BIO_EMP_SYNC_LINE_JOB ON BIO_EMPLOYEE_SYNC_LINE (JOB_ID);

CREATE OR REPLACE TRIGGER TRG_BIO_EMP_SYNC_LINE_BI
BEFORE INSERT ON BIO_EMPLOYEE_SYNC_LINE FOR EACH ROW
BEGIN
  IF :NEW.LINE_ID IS NULL OR :NEW.LINE_ID = 0 THEN
    SELECT BIO_EMP_SYNC_LINE_SEQ.NEXTVAL INTO :NEW.LINE_ID FROM DUAL;
  END IF;
END;
/

COMMIT;