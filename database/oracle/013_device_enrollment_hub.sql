-- Multi-device enrollment hub: per-device enrollment rows + nav module.
-- Run once on GateEntryOracle schema (after BIO_DEVICE exists).

CREATE SEQUENCE BIO_DEV_ENROLL_SEQ START WITH 1 INCREMENT BY 1 NOCACHE NOCYCLE;

CREATE TABLE BIO_DEVICE_ENROLLMENT (
  ENROLLMENT_ID       NUMBER(18)       NOT NULL,
  BIO_DEVICE_ID       NUMBER(18)       NOT NULL,
  EMPLOYEE_ID         VARCHAR2(32)     NOT NULL,
  DISPLAY_NAME        VARCHAR2(200),
  DEPARTMENT          VARCHAR2(200),
  CARD_NUMBER         VARCHAR2(64),
  AUTHORITY           VARCHAR2(32),
  CHECK_TYPE          VARCHAR2(48),
  FACE_TEMPLATE_CNT   NUMBER(5)        DEFAULT 0 NOT NULL,
  BIOMETRIC_STATUS    VARCHAR2(48),
  ENROLLED_AT         TIMESTAMP,
  ENROLLED_SOURCE     VARCHAR2(64),
  LAST_FETCHED_AT     TIMESTAMP        DEFAULT SYSTIMESTAMP NOT NULL,
  FETCH_BATCH_ID      VARCHAR2(36),
  CREATED_BY          NUMBER(18),
  UPDATED_BY          NUMBER(18),
  CREATED_AT          TIMESTAMP        DEFAULT SYSTIMESTAMP NOT NULL,
  UPDATED_AT          TIMESTAMP        DEFAULT SYSTIMESTAMP NOT NULL,
  DELETED_AT          TIMESTAMP,
  CONSTRAINT PK_BIO_DEVICE_ENROLLMENT PRIMARY KEY (ENROLLMENT_ID),
  CONSTRAINT UQ_BIO_DEV_ENROLL_DEV_EMP UNIQUE (BIO_DEVICE_ID, EMPLOYEE_ID)
);

CREATE INDEX IX_BIO_DEV_ENROLL_DEVICE ON BIO_DEVICE_ENROLLMENT (BIO_DEVICE_ID);

CREATE INDEX IX_BIO_DEV_ENROLL_EMP ON BIO_DEVICE_ENROLLMENT (EMPLOYEE_ID);

CREATE TABLE BIO_DEVICE_ENROLLMENT_BATCH (
  BATCH_ID            VARCHAR2(36)     NOT NULL,
  DEVICE_COUNT        NUMBER(5)        DEFAULT 0 NOT NULL,
  ROW_COUNT           NUMBER(10)       DEFAULT 0 NOT NULL,
  CREATED_BY          NUMBER(18),
  CREATED_AT          TIMESTAMP        DEFAULT SYSTIMESTAMP NOT NULL,
  NOTE_TEXT           VARCHAR2(400),
  CONSTRAINT PK_BIO_DEV_ENROLL_BATCH PRIMARY KEY (BATCH_ID)
);

CREATE OR REPLACE TRIGGER TRG_BIO_DEV_ENROLL_BI
BEFORE INSERT ON BIO_DEVICE_ENROLLMENT FOR EACH ROW
BEGIN
  IF :NEW.ENROLLMENT_ID IS NULL OR :NEW.ENROLLMENT_ID = 0 THEN
    SELECT BIO_DEV_ENROLL_SEQ.NEXTVAL INTO :NEW.ENROLLMENT_ID FROM DUAL;
  END IF;
  :NEW.CREATED_AT := NVL(:NEW.CREATED_AT, SYSTIMESTAMP);
  :NEW.UPDATED_AT := SYSTIMESTAMP;
END;
/

-- Nav: Enrollment hub
INSERT INTO SEC_MODULE (MODULE_CODE, MODULE_NAME, ROUTE_PATH, ICON_CLASS, SORT_ORDER, CREATED_BY)
SELECT 'device_enroll_hub', 'Enrollment hub', '/Device/EnrollmentHub', 'bi-layers', 34, 1 FROM DUAL
WHERE NOT EXISTS (SELECT 1 FROM SEC_MODULE WHERE MODULE_CODE = 'device_enroll_hub');

INSERT INTO SEC_PERMISSION (MODULE_ID, PERMISSION_CODE, PERMISSION_NAME, CREATED_BY)
SELECT m.MODULE_ID, 'device_enroll_hub.view', 'Multi-device enrollment fetch and compare', 1 FROM SEC_MODULE m
WHERE m.MODULE_CODE = 'device_enroll_hub'
  AND NOT EXISTS (SELECT 1 FROM SEC_PERMISSION WHERE PERMISSION_CODE = 'device_enroll_hub.view');

INSERT INTO SEC_PERMISSION (MODULE_ID, PERMISSION_CODE, PERMISSION_NAME, CREATED_BY)
SELECT m.MODULE_ID, 'device_enroll_hub.save', 'Save device enrollments to portal DB', 1 FROM SEC_MODULE m
WHERE m.MODULE_CODE = 'device_enroll_hub'
  AND NOT EXISTS (SELECT 1 FROM SEC_PERMISSION WHERE PERMISSION_CODE = 'device_enroll_hub.save');

INSERT INTO SEC_ROLE_PERMISSION (ROLE_ID, PERMISSION_ID, CREATED_BY)
SELECT r.ROLE_ID, p.PERMISSION_ID, 1
FROM SEC_ROLE r
CROSS JOIN SEC_PERMISSION p
WHERE r.ROLE_CODE = 'SUPER_ADMIN' AND p.PERMISSION_CODE IN ('device_enroll_hub.view', 'device_enroll_hub.save')
  AND NOT EXISTS (
    SELECT 1 FROM SEC_ROLE_PERMISSION rp
    WHERE rp.ROLE_ID = r.ROLE_ID AND rp.PERMISSION_ID = p.PERMISSION_ID AND rp.DELETED_AT IS NULL
  );

INSERT INTO SEC_ROLE_PERMISSION (ROLE_ID, PERMISSION_ID, CREATED_BY)
SELECT DISTINCT rp.ROLE_ID, p_new.PERMISSION_ID, 1
FROM SEC_ROLE_PERMISSION rp
JOIN SEC_PERMISSION p_dev ON p_dev.PERMISSION_ID = rp.PERMISSION_ID AND p_dev.PERMISSION_CODE = 'device_users.view' AND p_dev.DELETED_AT IS NULL
CROSS JOIN SEC_PERMISSION p_new
WHERE p_new.PERMISSION_CODE = 'device_enroll_hub.view' AND p_new.DELETED_AT IS NULL
  AND rp.DELETED_AT IS NULL
  AND NOT EXISTS (
    SELECT 1 FROM SEC_ROLE_PERMISSION x
    WHERE x.ROLE_ID = rp.ROLE_ID AND x.PERMISSION_ID = p_new.PERMISSION_ID AND x.DELETED_AT IS NULL
  );

COMMIT;