-- Gate Entry · multiple biometric devices + portal setup flag
-- Run as entrygate_surv (F5). Safe to re-run seed section only if modules exist.

CREATE SEQUENCE BIO_DEVICE_SEQ START WITH 1 INCREMENT BY 1 NOCACHE NOCYCLE;

CREATE TABLE BIO_PORTAL_SETTING (
  SETTING_KEY   VARCHAR2(64)   NOT NULL,
  SETTING_VALUE VARCHAR2(512),
  UPDATED_AT    TIMESTAMP(6)   DEFAULT SYSTIMESTAMP NOT NULL,
  CONSTRAINT PK_BIO_PORTAL_SETTING PRIMARY KEY (SETTING_KEY)
);

CREATE TABLE BIO_DEVICE (
  DEVICE_ID              NUMBER(18)     NOT NULL,
  DEVICE_IP              VARCHAR2(64)   NOT NULL,
  DEVICE_PORT            NUMBER(5)      DEFAULT 9922 NOT NULL,
  ADMIN_ID               VARCHAR2(64),
  ADMIN_PASSWORD_PROTECT VARCHAR2(512),
  DEVICE_NAME            VARCHAR2(128)  NOT NULL,
  DEVICE_LOCATION        VARCHAR2(256),
  DEVICE_SERIAL          VARCHAR2(64),
  IS_ACTIVE              CHAR(1)        DEFAULT 'Y' NOT NULL,
  IS_PRIMARY             CHAR(1)        DEFAULT 'N' NOT NULL,
  LAST_SEEN_AT           TIMESTAMP(6),
  LAST_SYNC_ERROR        VARCHAR2(512),
  CREATED_BY             NUMBER(18),
  UPDATED_BY             NUMBER(18),
  DELETED_BY             NUMBER(18),
  CREATED_AT             TIMESTAMP(6)   DEFAULT SYSTIMESTAMP NOT NULL,
  UPDATED_AT             TIMESTAMP(6),
  DELETED_AT             TIMESTAMP(6),
  CONSTRAINT PK_BIO_DEVICE PRIMARY KEY (DEVICE_ID),
  CONSTRAINT CK_BIO_DEVICE_ACTIVE CHECK (IS_ACTIVE IN ('Y','N')),
  CONSTRAINT CK_BIO_DEVICE_PRIMARY CHECK (IS_PRIMARY IN ('Y','N'))
);

CREATE INDEX IX_BIO_DEVICE_IP ON BIO_DEVICE (DEVICE_IP);

CREATE OR REPLACE TRIGGER TRG_BIO_DEVICE_BI
BEFORE INSERT ON BIO_DEVICE FOR EACH ROW
BEGIN IF :NEW.DEVICE_ID IS NULL OR :NEW.DEVICE_ID = 0 THEN SELECT BIO_DEVICE_SEQ.NEXTVAL INTO :NEW.DEVICE_ID FROM DUAL; END IF; END;
/

ALTER TABLE BIOMETRIC_ATTENDANCE_LOG ADD (BIO_DEVICE_ID NUMBER(18));
CREATE INDEX IX_BIO_ATT_DEVICE ON BIOMETRIC_ATTENDANCE_LOG (BIO_DEVICE_ID);

INSERT INTO BIO_PORTAL_SETTING (SETTING_KEY, SETTING_VALUE)
SELECT 'SETUP_COMPLETE', 'N' FROM DUAL
WHERE NOT EXISTS (SELECT 1 FROM BIO_PORTAL_SETTING WHERE SETTING_KEY = 'SETUP_COMPLETE');

-- Module + permissions (skip if already seeded)
INSERT INTO SEC_MODULE (MODULE_CODE, MODULE_NAME, ROUTE_PATH, ICON_CLASS, SORT_ORDER, CREATED_BY)
SELECT 'devices', 'Devices', '/Admin/Devices', 'bi-hdd-network', 25, 1 FROM DUAL
WHERE NOT EXISTS (SELECT 1 FROM SEC_MODULE WHERE MODULE_CODE = 'devices');

INSERT INTO SEC_PERMISSION (MODULE_ID, PERMISSION_CODE, PERMISSION_NAME, CREATED_BY)
SELECT m.MODULE_ID, 'devices.view', 'View devices', 1 FROM SEC_MODULE m
WHERE m.MODULE_CODE = 'devices' AND NOT EXISTS (SELECT 1 FROM SEC_PERMISSION WHERE PERMISSION_CODE = 'devices.view');

INSERT INTO SEC_PERMISSION (MODULE_ID, PERMISSION_CODE, PERMISSION_NAME, CREATED_BY)
SELECT m.MODULE_ID, 'devices.manage', 'Add and edit devices', 1 FROM SEC_MODULE m
WHERE m.MODULE_CODE = 'devices' AND NOT EXISTS (SELECT 1 FROM SEC_PERMISSION WHERE PERMISSION_CODE = 'devices.manage');

INSERT INTO SEC_ROLE_PERMISSION (ROLE_ID, PERMISSION_ID, CREATED_BY)
SELECT r.ROLE_ID, p.PERMISSION_ID, 1 FROM SEC_ROLE r, SEC_PERMISSION p
WHERE r.ROLE_CODE = 'SUPER_ADMIN' AND p.PERMISSION_CODE IN ('devices.view', 'devices.manage')
AND NOT EXISTS (
  SELECT 1 FROM SEC_ROLE_PERMISSION x WHERE x.ROLE_ID = r.ROLE_ID AND x.PERMISSION_ID = p.PERMISSION_ID AND x.DELETED_AT IS NULL
);

