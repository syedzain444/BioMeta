PROMPT Count by id (5001-5004) Oct-Nov 2025:
SELECT TRIM(EMPLOYEE_ID) id, COUNT(*) cnt,
       MIN(PUNCH_TIME) first_punch, MAX(PUNCH_TIME) last_punch
FROM BIOMETRIC_ATTENDANCE_LOG
WHERE PUNCH_TIME >= TO_DATE('2025-10-01','YYYY-MM-DD')
  AND PUNCH_TIME < TO_DATE('2025-11-05','YYYY-MM-DD')
  AND (TRIM(EMPLOYEE_ID) IN ('5001','5002','5003','5004','05001','05002','05003','05004')
       OR LTRIM(TRIM(EMPLOYEE_ID),'0') IN ('5001','5002','5003','5004'))
GROUP BY TRIM(EMPLOYEE_ID)
ORDER BY id;

PROMPT Sample IDs like 500% in range:
SELECT * FROM (
  SELECT DISTINCT TRIM(EMPLOYEE_ID) id FROM BIOMETRIC_ATTENDANCE_LOG
  WHERE PUNCH_TIME >= TO_DATE('2025-10-01','YYYY-MM-DD')
    AND EMPLOYEE_ID LIKE '500%'
  ORDER BY id
) WHERE ROWNUM <= 20;

